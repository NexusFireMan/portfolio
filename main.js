function applyTranslations(lang) {
    const activeLang = translations[lang] ? lang : "es";
    const dict = translations[activeLang];

    document.documentElement.lang = activeLang;
    document.title = dict["meta.title"];

    const metaDescription = document.getElementById("meta-description");
    const ogTitle = document.getElementById("og-title");
    const ogDescription = document.getElementById("og-description");
    if (metaDescription) metaDescription.content = dict["meta.description"];
    if (ogTitle) ogTitle.content = dict["meta.ogTitle"];
    if (ogDescription) ogDescription.content = dict["meta.ogDescription"];

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (key && dict[key]) {
            element.textContent = dict[key];
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
        const key = element.getAttribute("data-i18n-html");
        if (key && dict[key]) {
            element.innerHTML = dict[key];
        }
    });

    const langSelect = document.getElementById("lang-select");
    if (langSelect) {
        langSelect.setAttribute("aria-label", activeLang === "es" ? "Selector de idioma" : "Language selector");
    }

    const cvDownload = document.getElementById("cv-download");
    if (cvDownload) {
        cvDownload.setAttribute("href", dict["hero.cvFile"] || "CV_JavierDuran_ES.pdf");
    }

    try {
        localStorage.setItem("portfolio_lang", activeLang);
    } catch (error) {
        // localStorage may be blocked in some browsing modes.
    }
}

function getInitialLanguage() {
    try {
        const savedLanguage = localStorage.getItem("portfolio_lang");
        if (savedLanguage && translations[savedLanguage]) {
            return savedLanguage;
        }
    } catch (error) {
        // Ignore storage read errors and fallback to browser language.
    }

    return navigator.language && navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

const year = document.getElementById("year");
if (year) {
    year.textContent = new Date().getFullYear();
}

const initialLanguage = getInitialLanguage();
applyTranslations(initialLanguage);

const langSelect = document.getElementById("lang-select");
if (langSelect) {
    langSelect.value = initialLanguage;
    langSelect.addEventListener("change", (event) => {
        applyTranslations(event.target.value);
    });
}

